export async function GET() {
  try {
    let createdCount = 0;
    
    for (const blog of BLOGS) {
      // Check if it already exists to prevent duplicate seeding
      const existing = await prisma.blogPost.findUnique({
        where: { slug: blog.slug }
      });
      
      if (!existing) {
        await prisma.blogPost.create({
          data: {
            title: blog.title,
            slug: blog.slug,
            excerpt: blog.excerpt,
            content: blog.content,
            coverImage: blog.coverImage,
            published: blog.published,
            author: "Zica Bella Editorial Team"
          }
        });
        createdCount++;
      }
    }
    
    return NextResponse.json({
      success: true,
      message: `Seeding completed successfully. Created ${createdCount} blog posts.`,
    });
  } catch (error: any) {
    console.error("Error seeding blogs:", error);
    return NextResponse.json({
      success: false,
      error: error.message || "Unknown error seeding blogs"
    }, { status: 500 });
  }
}
